end

function r = ternary(c, a, b)
if c, r = a; else, r = b; end
end

% Plain Hamilton quaternion helpers for building test inputs (not under test)
function r = quat_mul(q, p)
r = [q(1)*p(1) - q(2)*p(2) - q(3)*p(3) - q(4)*p(4), ...
     q(1)*p(2) + q(2)*p(1) + q(3)*p(4) - q(4)*p(3), ...
     q(1)*p(3) - q(2)*p(4) + q(3)*p(1) + q(4)*p(2), ...
     q(1)*p(4) + q(2)*p(3) - q(3)*p(2) + q(4)*p(1)];
end

function r = quat_conj(q)
r = [q(1), -q(2), -q(3), -q(4)];
end

function q = rv2q(rv)
a = norm(rv);
if a < 1e-15, q = [1 0 0 0]; return; end
q = [cos(a / 2), sin(a / 2) * rv / a];
end

function w = rot(q, v)
p = quat_mul(quat_mul(q, [0, v(:)']), quat_conj(q));
w = p(2:4);
end
